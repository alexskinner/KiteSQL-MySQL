#[cfg(test)]
mod tests {
    use super::rewrite_create_table;
    use sqlparser::ast::Statement;
    use sqlparser::dialect::MySqlDialect;
    use sqlparser::parser::Parser;

    fn rewrite(sql: &str) -> Result<String, String> {
        let mut stmt = Parser::parse_sql(&MySqlDialect {}, sql).unwrap().remove(0);
        let Statement::CreateTable(create) = &mut stmt else {
            unreachable!()
        };
        rewrite_create_table(create).map_err(|e| e.to_string())?;
        // sqlparser pads the sequence options and the empty table options with spaces
        Ok(stmt
            .to_string()
            .replace("( ", "(")
            .replace(" )", ")")
            .trim_end()
            .to_string())
    }

    #[test]
    fn auto_increment_becomes_an_identity_column() {
        assert_eq!(
            rewrite("CREATE TABLE t (id INT AUTO_INCREMENT PRIMARY KEY, v INT) AUTO_INCREMENT = 7")
                .unwrap(),
            "CREATE TABLE t (id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 7), v INT)"
        );
        assert_eq!(
            rewrite("CREATE TABLE t (id SERIAL, PRIMARY KEY (id))").unwrap(),
            "CREATE TABLE t (id SERIAL NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY, PRIMARY KEY (id))"
        );
        assert!(
            rewrite("CREATE TABLE t (k INT PRIMARY KEY, id INT AUTO_INCREMENT)")
                .unwrap_err()
                .contains("only one auto column")
        );
        assert!(rewrite(
            "CREATE TABLE t (id INT AUTO_INCREMENT PRIMARY KEY, j INT AUTO_INCREMENT UNIQUE)"
        )
        .unwrap_err()
        .contains("only one auto column"));
        assert_eq!(
            rewrite("CREATE TABLE t (id INT PRIMARY KEY) AUTO_INCREMENT = 7").unwrap(),
            "CREATE TABLE t (id INT PRIMARY KEY) AUTO_INCREMENT = 7"
        );
    }
}
