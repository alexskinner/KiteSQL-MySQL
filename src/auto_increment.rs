//! MySQL's `AUTO_INCREMENT` on the core identity column.
//!
//! `CREATE TABLE` columns marked `AUTO_INCREMENT` (and `SERIAL` columns, which MySQL defines
//! as `BIGINT UNSIGNED NOT NULL AUTO_INCREMENT UNIQUE`) become
//! `GENERATED BY DEFAULT AS IDENTITY`; the table option `AUTO_INCREMENT = n` becomes the
//! identity's `START WITH n`. `LAST_INSERT_ID()` reads the value the core records for the
//! last insert on this thread.

use kite_sql::errors::DatabaseError;
use kite_sql::expression::function::scala::{FuncMonotonicity, ScalarFunctionImpl};
use kite_sql::expression::function::{FunctionSummary, PersistencePolicy};
use kite_sql::planner::{ExprRef, MetaArena};
use kite_sql::types::tuple::Input;
use kite_sql::types::value::DataValue;
use kite_sql::types::LogicalType;
use sqlparser::ast::{
    ColumnDef, ColumnOption, ColumnOptionDef, CreateTable, CreateTableOptions, DataType, Expr,
    GeneratedAs, KeyOrIndexDisplay, NullsDistinctOption, ObjectNamePart, SequenceOptions,
    SqlOption, TableConstraint, UniqueConstraint, Value,
};
use std::sync::Arc;

/// MySQL error 1075.
const ONE_AUTO_COLUMN_AS_KEY: &str =
    "Incorrect table definition; there can be only one auto column and it must be defined as a key";

fn is_auto_increment(option: &ColumnOption) -> bool {
    matches!(option, ColumnOption::DialectSpecific(tokens)
        if tokens.len() == 1 && tokens[0].to_string().eq_ignore_ascii_case("AUTO_INCREMENT"))
}

fn is_serial(data_type: &DataType) -> bool {
    matches!(data_type, DataType::Custom(name, modifiers)
        if modifiers.is_empty()
            && name.0.len() == 1
            && matches!(&name.0[0], ObjectNamePart::Identifier(ident)
                if ident.value.eq_ignore_ascii_case("serial")))
}

/// The `AUTO_INCREMENT = n` table option, removed from the options.
fn take_start(options: &mut CreateTableOptions) -> Result<Option<i64>, DatabaseError> {
    let (CreateTableOptions::Plain(options) | CreateTableOptions::With(options)) = options else {
        return Ok(None);
    };
    let mut start = None;
    let mut error = None;
    options.retain(|option| match option {
        SqlOption::KeyValue { key, value } if key.value.eq_ignore_ascii_case("AUTO_INCREMENT") => {
            match value {
                Expr::Value(v) => match &v.value {
                    Value::Number(n, _) => match n.parse::<i64>() {
                        Ok(n) => start = Some(n),
                        Err(_) => error = Some(n.clone()),
                    },
                    other => error = Some(other.to_string()),
                },
                other => error = Some(other.to_string()),
            }
            false
        }
        _ => true,
    });
    if let Some(value) = error {
        return Err(DatabaseError::InvalidValue(format!(
            "invalid AUTO_INCREMENT table option: {value}"
        )));
    }
    // MySQL ignores AUTO_INCREMENT = 0.
    Ok(start.filter(|n| *n > 0))
}

fn first_key_column(expr: &Expr) -> Option<&str> {
    match expr {
        Expr::Identifier(ident) => Some(ident.value.as_str()),
        Expr::CompoundIdentifier(idents) => idents.last().map(|ident| ident.value.as_str()),
        _ => None,
    }
}

/// Whether `column` leads some index of the table (MySQL requires it of an auto column).
fn is_key(column: &ColumnDef, constraints: &[TableConstraint]) -> bool {
    let column_key = column.options.iter().any(|option| {
        matches!(
            option.option,
            ColumnOption::PrimaryKey(_) | ColumnOption::Unique(_)
        )
    });
    column_key
        || constraints.iter().any(|constraint| {
            let first = match constraint {
                TableConstraint::PrimaryKey(c) => c.columns.first(),
                TableConstraint::Unique(c) => c.columns.first(),
                TableConstraint::Index(c) => c.columns.first(),
                _ => None,
            };
            first
                .and_then(|c| first_key_column(&c.column.expr))
                .is_some_and(|name| name.eq_ignore_ascii_case(&column.name.value))
        })
}

fn identity(start: Option<i64>) -> ColumnOptionDef {
    ColumnOptionDef {
        name: None,
        option: ColumnOption::Generated {
            generated_as: GeneratedAs::ByDefault,
            sequence_options: Some(
                start
                    .map(|n| {
                        vec![SequenceOptions::StartWith(
                            Expr::value(Value::Number(n.to_string(), false)),
                            true,
                        )]
                    })
                    .unwrap_or_default(),
            ),
            generation_expr: None,
            generation_expr_mode: None,
            generated_keyword: true,
        },
    }
}

/// Rewrites `AUTO_INCREMENT` and `SERIAL` columns of `CREATE TABLE` into an identity column.
pub(crate) fn rewrite_create_table(create: &mut CreateTable) -> Result<(), DatabaseError> {
    let auto_columns = create
        .columns
        .iter()
        .filter(|column| {
            is_serial(&column.data_type)
                || column.options.iter().any(|o| is_auto_increment(&o.option))
        })
        .count();
    if auto_columns == 0 {
        return Ok(());
    }
    if auto_columns > 1 {
        return Err(DatabaseError::InvalidValue(
            ONE_AUTO_COLUMN_AS_KEY.to_string(),
        ));
    }
    let start = take_start(&mut create.table_options)?;
    let constraints = create.constraints.clone();
    for column in create.columns.iter_mut() {
        let serial = is_serial(&column.data_type);
        if !serial && !column.options.iter().any(|o| is_auto_increment(&o.option)) {
            continue;
        }
        column.options.retain(|o| !is_auto_increment(&o.option));
        if serial {
            column
                .options
                .retain(|o| !matches!(o.option, ColumnOption::Null));
            if !column
                .options
                .iter()
                .any(|o| matches!(o.option, ColumnOption::NotNull))
            {
                column.options.push(ColumnOptionDef {
                    name: None,
                    option: ColumnOption::NotNull,
                });
            }
            if !column
                .options
                .iter()
                .any(|o| matches!(o.option, ColumnOption::Unique(_)))
            {
                column.options.push(ColumnOptionDef {
                    name: None,
                    option: ColumnOption::Unique(UniqueConstraint {
                        name: None,
                        index_name: None,
                        index_type_display: KeyOrIndexDisplay::None,
                        index_type: None,
                        columns: vec![],
                        index_options: vec![],
                        characteristics: None,
                        nulls_distinct: NullsDistinctOption::None,
                    }),
                });
            }
        } else if !is_key(column, &constraints) {
            return Err(DatabaseError::InvalidValue(
                ONE_AUTO_COLUMN_AS_KEY.to_string(),
            ));
        }
        column.options.push(identity(start));
    }
    Ok(())
}

/// `LAST_INSERT_ID()`: the first value generated by the last INSERT on this connection that
/// generated any (0 if none), or the value last set with `LAST_INSERT_ID(expr)`.
/// `LAST_INSERT_ID(expr)` returns `expr` and makes it the value; NULL returns NULL and sets 0.
#[derive(Debug)]
pub struct LastInsertId {
    summary: FunctionSummary,
}

impl LastInsertId {
    pub fn new(with_arg: bool) -> Arc<Self> {
        Arc::new(Self {
            summary: FunctionSummary {
                name: "last_insert_id".into(),
                arg_types: if with_arg {
                    vec![LogicalType::Bigint]
                } else {
                    vec![]
                },
                persistence: PersistencePolicy::Transient,
            },
        })
    }
}

/// MySQL reports the value as BIGINT UNSIGNED: negative values wrap around.
fn unsigned(value: i128) -> DataValue {
    DataValue::UInt64(value as u64)
}

impl ScalarFunctionImpl for LastInsertId {
    fn eval(
        &self,
        args: &[ExprRef],
        arena: &(dyn MetaArena + '_),
        tuple: Option<&dyn Input>,
    ) -> Result<DataValue, DatabaseError> {
        let Some(arg) = args.first() else {
            return Ok(unsigned(kite_sql::identity::last_generated().unwrap_or(0)));
        };
        let value = arena.expression(*arg).eval(arena, tuple)?.into_owned();
        if value.is_null() {
            kite_sql::identity::set_last_generated(Some(0));
            return Ok(DataValue::Null);
        }
        let value = match value.cast(&LogicalType::Bigint)? {
            DataValue::Int64(v) => v as i128,
            _ => 0,
        };
        kite_sql::identity::set_last_generated(Some(value));
        Ok(unsigned(value))
    }

    fn monotonicity(&self) -> Option<FuncMonotonicity> {
        None
    }

    fn return_type(&self) -> &LogicalType {
        &LogicalType::UBigint
    }

    fn summary(&self) -> &FunctionSummary {
        &self.summary
    }
}

